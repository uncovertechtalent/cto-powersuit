#!/usr/bin/env python3
"""Tests for the local review runner (skills/change-review/review-pr.sh).

Each case runs the whole script against fakes: a `gh` that serves a pull request from a local git
repository (and refuses the diff above 300 files on demand), a `claude` that records what the model
would have been given and answers with a canned review, and a `git` that only reports a fixed origin
for the reviewer cache. Nothing touches the network or the real home folder. Cases:

- a diff `gh` can serve goes to the model unchanged, and pr.json says it came from `gh`;
- a diff `gh` refuses as too large is built from the checkout (merge base, not the base tip), with the
  base branch more than 200 commits ahead, and pr.json and the prompt say so;
- a diff over the size limit is reduced: hand-written files whole, generated files as a stat and a sample;
- every path without a review exits non-zero with a message (gh failures, an empty diff, a base branch
  that cannot be fetched, a model that fails or returns an empty comment).

Standard library only, Python 3.9+, needs git, jq and bash.

Usage: python3 plugins/sdlc/tests/test_review_pr.py [-v]
"""
import json, os, shutil, subprocess, sys, tempfile
from pathlib import Path

sys.dont_write_bytecode = True

SCRIPT = Path(__file__).resolve().parent.parent / "skills/change-review/review-pr.sh"
VERBOSE = "-v" in sys.argv
GIT = shutil.which("git")
TOO_LARGE = ("could not find pull request diff: HTTP 406: Sorry, the diff exceeded the maximum number of files (300)\n"
             "PullRequest.diff too_large\n")

FAKE_GH = """#!/usr/bin/env python3
import json, os, subprocess, sys
a, env = sys.argv[1:], os.environ
if a[:2] == ["pr", "view"]:
    if env.get("FAKE_VIEW_FAIL"):
        sys.stderr.write("GraphQL: Could not resolve to a PullRequest\\n"); sys.exit(1)
    pr = open(env["FAKE_PR_JSON"]).read()
    sys.stdout.write(json.loads(pr)["headRefOid"] + "\\n" if "--jq" in a else pr)
elif a[:2] == ["repo", "clone"]:
    subprocess.run(["git", "clone", "-q", "--depth", "1", "file://" + env["FAKE_ORIGIN"], a[3]], check=True)
elif a[:2] == ["pr", "checkout"]:
    subprocess.run(["git", "fetch", "-q", "origin", "refs/pull/%s/head" % a[2]], check=True)
    subprocess.run(["git", "checkout", "-q", "--detach", "FETCH_HEAD"], check=True)
elif a[:2] == ["pr", "diff"]:
    mode = env["FAKE_DIFF_MODE"]
    if mode == "toolarge":
        sys.stderr.write(env["FAKE_TOO_LARGE"]); sys.exit(1)
    if mode == "error":
        sys.stderr.write("HTTP 500: Server Error\\n"); sys.exit(1)
    sys.stdout.write("" if mode == "empty" else open(env["FAKE_DIFF_FILE"]).read())
else:
    sys.stderr.write("fake gh: unexpected " + " ".join(a) + "\\n"); sys.exit(2)
"""

FAKE_CLAUDE = """#!/usr/bin/env python3
import json, os, shutil, sys
a, env = sys.argv[1:], os.environ
out = env["FAKE_OUT"]
os.makedirs(out, exist_ok=True)
open(os.path.join(out, "prompt.txt"), "w").write(a[1])
shutil.copytree(a[a.index("--add-dir") + 1], os.path.join(out, "pr"))
mode = env.get("FAKE_CLAUDE_MODE", "ok")
if mode == "fail":
    sys.exit(1)
if mode == "error":
    print(json.dumps({"is_error": True, "subtype": "error_max_turns", "num_turns": 40, "result": "ran out of turns"}))
    sys.exit(0)
comment = " \\n" if mode == "empty" else "## Change review with local context\\n\\nNo findings.\\n"
print(json.dumps({"structured_output": {"comment": comment, "block": 0, "should": 0, "note": 0, "kb_queries": []},
                  "num_turns": 3, "duration_ms": 1000, "total_cost_usd": 0.1, "permission_denials": []}))
"""

# Reports a fixed origin for the reviewer cache (the real one is a github.com URL), and is git otherwise.
FAKE_GIT = """#!/bin/sh
if [ "$3" = remote ] && [ "$4" = get-url ]; then echo https://github.com/test/suit; exit 0; fi
exec %s "$@"
"""


def git(cwd, *args, stdin=None):
    env = dict(os.environ, GIT_AUTHOR_NAME="Dev", GIT_AUTHOR_EMAIL="d@example.com",
               GIT_COMMITTER_NAME="Dev", GIT_COMMITTER_EMAIL="d@example.com")
    p = subprocess.run([GIT, "-c", "init.defaultBranch=main", "-c", "commit.gpgsign=false", *args],
                       cwd=cwd, env=env, check=True, capture_output=True, text=True, input=stdin)
    return p.stdout.strip()


def write(root, files):
    for name, text in files.items():
        f = Path(root) / name
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text)


def build_origin(path):
    """main at c1 with hand-written and generated files; a pull request branch that edits all of them;
    then 210 more commits on main and one that adds README.md, so the base tip is far past the fork."""
    path.mkdir()
    git(path, "init", "-q")
    page = "<!-- generated by build.py; do not edit -->\n<nav>%s</nav>\n<p>%d</p>\n"
    note = "# Note %d\nNav: %s\nbody\n"
    base = {".gitattributes": "gen/* linguist-generated\n", "src/app.py": 'print("v1")\n', "docs/unique.md": "one " + "x" * 2000 + "\n",
            "package-lock.json": '{"v": 1}\n', "gen/data.json": '{"n": 1}\n'}
    for i in range(25):
        base["site/page%02d.html" % i] = page % ("Docs", i)
    for i in range(22):
        base["notes/n%02d.md" % i] = note % (i, "Docs")
    for i in range(3):
        base["misc/m%d.md" % i] = "foo %d\nkeep\n" % i
    write(path, base)
    git(path, "add", "-A")
    git(path, "commit", "-q", "-m", "base")
    fork = git(path, "rev-parse", "HEAD")
    git(path, "checkout", "-q", "-b", "feature")
    change = {"src/app.py": 'print("v2")\n', "docs/unique.md": "two " + "y" * 2000 + "\n", "package-lock.json": '{"v": 2}\n', "gen/data.json": '{"n": 2}\n'}
    for i in range(25):
        change["site/page%02d.html" % i] = page % ("Map", i)
    for i in range(22):
        change["notes/n%02d.md" % i] = note % (i, "Map")
    for i in range(3):
        change["misc/m%d.md" % i] = "bar %d\nkeep\n" % i
    write(path, change)
    git(path, "add", "-A")
    git(path, "commit", "-q", "-m", "change")
    head = git(path, "rev-parse", "HEAD")
    git(path, "update-ref", "refs/pull/7/head", head)
    git(path, "checkout", "-q", "main")
    stream = "".join("commit refs/heads/main\ncommitter Dev <d@example.com> %d +0000\ndata 5\nmore\n%s\n" % (
        1700000000 + n, "from refs/heads/main^0" if n == 0 else "") for n in range(210))
    git(path, "fast-import", "--quiet", "--force", stdin=stream)
    git(path, "reset", "-q", "--hard", "main")
    write(path, {"README.md": "late change on main\n"})
    git(path, "add", "-A")
    git(path, "commit", "-q", "-m", "late")
    return fork, head, git(path, "diff", fork, head) + "\n"


def run_case(world, name, diff_mode="ok", limit=None, claude="ok", view_fail=False, base="main"):
    out = world["tmp"] / ("out-" + name)
    home = world["tmp"] / ("home-" + name)
    (home / ".cache").mkdir(parents=True)
    pr = dict(world["pr"], baseRefName=base)
    (world["tmp"] / "pr.json").write_text(json.dumps(pr))
    env = dict(os.environ, HOME=str(home), TMPDIR=str(world["tmp"]), PATH=str(world["bin"]) + os.pathsep + os.environ["PATH"],
               POWERSUIT_REPO="test/suit", POWERSUIT_CACHE=str(world["cache"]), FAKE_ORIGIN=str(world["origin"]),
               FAKE_PR_JSON=str(world["tmp"] / "pr.json"), FAKE_DIFF_MODE=diff_mode, FAKE_DIFF_FILE=str(world["tmp"] / "expected.diff"),
               FAKE_TOO_LARGE=TOO_LARGE, FAKE_OUT=str(out), FAKE_CLAUDE_MODE=claude, GIT_TERMINAL_PROMPT="0")
    env.pop("POWERSUIT_OVERLAY", None)
    env.pop("PRIVATE_TERMS", None)
    if limit:
        env["POWERSUIT_MAX_DIFF_BYTES"] = str(limit)
    if view_fail:
        env["FAKE_VIEW_FAIL"] = "1"
    p = subprocess.run([str(SCRIPT), "test/repo", "7", "--allow-unscanned"], env=env, stdin=subprocess.DEVNULL,
                       capture_output=True, text=True, timeout=300)
    if VERBOSE:
        print("--- %s: exit %d\n%s%s" % (name, p.returncode, p.stdout, p.stderr))
    return p, out


def read(out, name):
    f = out / name
    return f.read_text() if f.is_file() else None


def check(problems, cond, text):
    if not cond:
        problems.append(text)


def case_gh_serves_the_diff(world):
    p, out = run_case(world, "gh-ok")
    problems = []
    check(problems, p.returncode == 0, "exit %d: %s" % (p.returncode, p.stderr.strip()))
    check(problems, read(out, "pr/pr.diff") == world["expected"], "pr.diff differs from the diff gh served")
    meta = json.loads(read(out, "pr/pr.json") or "{}")
    check(problems, meta.get("diff", {}).get("source") == "gh" and meta["diff"].get("mode") == "full", "pr.json .diff is %s" % meta.get("diff"))
    check(problems, "built by this script" not in (read(out, "prompt.txt") or "") and "is reduced" not in (read(out, "prompt.txt") or ""),
          "the prompt mentions a fallback or a reduced diff")
    check(problems, not (out / "pr/pr.generated-stat.txt").exists(), "a stat file exists for a small diff")
    return problems


def case_fallback(world):
    p, out = run_case(world, "fallback", diff_mode="toolarge")
    problems = []
    check(problems, p.returncode == 0, "exit %d: %s" % (p.returncode, p.stderr.strip()))
    got = read(out, "pr/pr.diff")
    check(problems, got == world["expected"], "pr.diff is not the three-dot diff from the merge base")
    check(problems, got is not None and "README.md" not in got, "pr.diff holds a change made on the base branch after the fork")
    meta = json.loads(read(out, "pr/pr.json") or "{}")
    check(problems, meta.get("diff", {}).get("source") == "local-git" and meta["diff"].get("mergeBase") == world["fork"],
          "pr.json .diff is %s, want local-git at %s" % (meta.get("diff"), world["fork"]))
    prompt = read(out, "prompt.txt") or ""
    check(problems, "built by this script" in prompt and world["fork"][:12] in prompt, "the prompt does not say the diff was built locally")
    check(problems, "building the diff from the checkout" in p.stdout, "no message about the fallback on stdout")
    return problems


def case_reduced(world, diff_mode, name):
    p, out = run_case(world, name, diff_mode=diff_mode, limit=3000)
    problems = []
    check(problems, p.returncode == 0, "exit %d: %s" % (p.returncode, p.stderr.strip()))
    meta = json.loads(read(out, "pr/pr.json") or "{}")
    info = meta.get("diff", {})
    want = {"mode": "reduced", "generatedFiles": 49, "otherFiles": 5, "limitBytes": 3000,
            "reasons": {"header": 25, "repeat": 22, "name": 1, "attribute": 1}}
    for k, v in want.items():
        check(problems, info.get(k) == v, "pr.json .diff.%s is %r, want %r" % (k, info.get(k), v))
    check(problems, len(info.get("sampled", [])) == 4, "sampled %s, want 4 groups" % info.get("sampled"))
    check(problems, info.get("cutLines") == 2, "cutLines is %r, want 2 (the long line removed and the long line added)" % info.get("cutLines"))
    diff = read(out, "pr/pr.diff") or ""
    check(problems, max((len(l) for l in diff.splitlines()), default=0) < 600 and " more characters cut]" in diff,
          "a long line is not cut and marked in pr.diff")
    for kept in ("src/app.py", "docs/unique.md", "misc/m0.md", "misc/m2.md"):
        check(problems, "diff --git a/%s " % kept in diff, "pr.diff lacks the hand-written %s" % kept)
    for left in ("site/page", "notes/n", "package-lock.json", "gen/data.json"):
        check(problems, left not in diff, "pr.diff still holds %s" % left)
    stat = read(out, "pr/pr.generated-stat.txt") or ""
    for line in ("+1 -1 g1 header site/page00.html", "+1 -1 g2 repeat notes/n21.md", "+1 -1 - name package-lock.json",
                 "+1 -1 - attribute gen/data.json"):
        check(problems, line in stat.splitlines(), "stat lacks the line %r" % line)
    check(problems, len([l for l in stat.splitlines() if not l.startswith("#")]) == 49, "stat does not list 49 files")
    sample = read(out, "pr/pr.generated-sample.diff") or ""
    check(problems, sample.count("diff --git ") == 4 and "site/page00.html" in sample and "notes/n00.md" in sample,
          "the sample is not one file per group")
    check(problems, [x["path"] for x in meta.get("files", [])] == sorted(x["path"] for x in meta.get("files", [])) and
          len(meta.get("files", [])) == 5, "pr.json files holds %d entries, want the 5 hand-written files" % len(meta.get("files", [])))
    prompt = read(out, "prompt.txt") or ""
    check(problems, "pr.diff is reduced" in prompt and "sampled" in prompt and "cut" in prompt, "the prompt does not say the diff is reduced")
    if diff_mode == "toolarge":
        check(problems, info.get("source") == "local-git" and "built by this script" in prompt, "the fallback is not recorded next to the reduction")
    return problems


def case_stops(world):
    problems = []
    cases = [
        ("gh-error", dict(diff_mode="error"), "gh pr diff failed"),
        ("empty-diff", dict(diff_mode="empty"), "empty diff"),
        ("view-fails", dict(view_fail=True), "cannot read"),
        ("no-base", dict(diff_mode="toolarge", base="no-such-branch"), "could not fetch"),
        ("claude-fails", dict(claude="fail"), "no review"),
        ("claude-errors", dict(claude="error"), "no review"),
        ("empty-comment", dict(claude="empty"), "no review"),
    ]
    for name, kwargs, want in cases:
        p, out = run_case(world, name, **kwargs)
        check(problems, p.returncode == 1, "%s: exit %d, want 1" % (name, p.returncode))
        check(problems, want in p.stderr, "%s: stderr has no %r: %s" % (name, want, p.stderr.strip()[-200:]))
        check(problems, "no review was produced" in p.stderr, "%s: stderr does not say that no review was produced" % name)
    p, out = run_case(world, "gh-error-no-model", diff_mode="error")
    check(problems, not (out / "prompt.txt").exists(), "the model ran although the diff could not be read")
    return problems


def main():
    if not SCRIPT.is_file() or not os.access(SCRIPT, os.X_OK):
        print("FAIL %s is missing or not executable" % SCRIPT)
        sys.exit(1)
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp).resolve()
        origin = tmp / "origin"
        fork, head, expected = build_origin(origin)
        (tmp / "expected.diff").write_text(expected)
        suit = tmp / "suit"
        suit.mkdir()
        git(suit, "init", "-q")
        write(suit, {"plugins/sdlc/.claude-plugin/plugin.json": '{"version": "9.9.9"}\n'})
        git(suit, "add", "-A")
        git(suit, "commit", "-q", "-m", "suit")
        git(tmp, "clone", "-q", str(suit), str(tmp / "cache"))
        bin_dir = tmp / "bin"
        bin_dir.mkdir()
        for name, text in (("gh", FAKE_GH), ("claude", FAKE_CLAUDE), ("git", FAKE_GIT % GIT)):
            (bin_dir / name).write_text(text)
            (bin_dir / name).chmod(0o755)
        pr = {"number": 7, "title": "Change the nav label", "body": "", "author": {"login": "someone", "is_bot": False}, "isDraft": False,
              "isCrossRepository": False, "commits": [], "additions": 1, "deletions": 1, "closingIssuesReferences": [],
              "headRefOid": head, "state": "OPEN",
              "files": [{"path": p, "additions": 1, "deletions": 1} for p in sorted(git(origin, "diff", "--name-only", fork, head).splitlines())]}
        world = {"tmp": tmp, "bin": bin_dir, "origin": origin, "cache": tmp / "cache", "pr": pr, "fork": fork, "expected": expected}
        cases = [("gh serves the diff", case_gh_serves_the_diff), ("fallback when gh refuses", case_fallback),
                 ("reduced diff", lambda w: case_reduced(w, "ok", "reduced")),
                 ("fallback and reduced diff", lambda w: case_reduced(w, "toolarge", "both")),
                 ("every stop says so", case_stops)]
        failures = 0
        for label, fn in cases:
            problems = fn(world)
            failures += len(problems)
            print("%s %s" % ("ok  " if not problems else "FAIL", label))
            for problem in problems:
                print("     " + problem)
    print("%d cases, %d failures" % (len(cases), failures))
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
